"""Writes a host scenario (x0x_host) that plays the 808 / 909 / 303 / PAD demo over MIDI, 124 BPM:
bars 1-2 the 808, 3-4 + the 303, 5-8 + the PAD (CHORD AUTO in C: Am7 Fmaj7 Cmaj7 G7), 7-8 + 909 hats.
   make_demo.py OUT.x0x [solo: 808|303|pad]"""
import sys
out = open(sys.argv[1], "w")
solo = sys.argv[2] if len(sys.argv) > 2 else None
BPM = 124
ST = 60000.0 / BPM / 4                       # a 16th, ms
P = lambda *a: out.write(" ".join(str(x) for x in a) + "\n")
P("# generated by tests/pad/make_demo.py")
P("wait 400")
P("param 2 1 4 2")                           # PAD CHORD = AUTO
P("param 2 1 5 0")                           # KEY = C
P("wav demo.wav")
ev = {}                                      # 16th -> [midi msgs]
def at(step, *msg): ev.setdefault(step, []).append(msg)
bars = 8 if not solo else (2 if solo == "808" else 4)
k8, k9, a303, pad = 0x9A, 0x99, 0x91, 0x92
for bar in range(bars):
    b = bar * 16
    on = lambda part: (solo == part) or (not solo and {"808": 0, "303": 2, "pad": 4, "909": 6}[part] <= bar)
    if on("808"):
        for s in (0, 4, 8, 12): at(b + s, k8, 36, 110)
        for s in (4, 12): at(b + s, k8, 39, 100)
        for s in (2, 6, 10, 14): at(b + s, k8, 42, 90)
        at(b + 14, k8, 46, 80)
    if not solo and on("909"):
        for s in range(16): at(b + s, k9, 42, 70 if s % 2 else 100)
    if on("303"):
        line = [(45, 1, 0), None, (45, 0, 0), (57, 0, 1), (55, 1, 0), None, (45, 0, 0), (48, 1, 1),
                (52, 0, 0), None, (45, 1, 0), (57, 0, 0), (45, 0, 1), (43, 0, 0), None, (45, 1, 0)]
        for s, n in enumerate(line):
            if n:
                note, acc, slide = n
                at(b + s, a303, note, 120 if acc else 80)
                at(b + s + (1 if slide else 0.5), 0x81, note, 0)   # a slide: held into the next step
    if on("pad"):
        root = [57, 53, 48, 55][bar % 4]
        at(b, pad, root, 90)
        at(b + 15.5, 0x82, root, 0)
end = bars * 16 + 8
t = 0.0
steps = sorted(set(list(ev.keys()) + [end]))
for s in steps:
    w = s * ST - t
    if w >= 1:
        P("wait", int(round(w)))
        t += int(round(w))
    for m in ev.get(s, []):
        P("midi", " ".join("%02X" % x for x in m))
P("wavstop")
